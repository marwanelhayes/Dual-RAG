"""Extract deterministic specification signals from structured table chunks."""

from collections import Counter
import json
import re

import configure as cfg
from ingest import load_chunks
from naming import identifier_tokens, normalize_identifier

SCHEMA_VERSION = 5


EXPLICIT_NAME_HEADERS = frozenset({"signal", "signal name", "port", "port name"})
GENERIC_NAME_HEADERS = frozenset({"name"})
NAME_HEADERS = EXPLICIT_NAME_HEADERS | GENERIC_NAME_HEADERS
WIDTH_HEADERS = frozenset({"width", "bit width", "size"})
DIRECTION_HEADERS = frozenset({"direction", "dir", "signal direction", "port direction"})
SOURCE_HEADERS = frozenset({"source", "driven by", "driver", "generated by", "sourced by"})
# A register allocation table names its rows by address instead of by port role.
ADDRESS_HEADERS = frozenset({"number", "address", "csr", "csr address"})
DESCRIPTION_HEADERS = frozenset({"description", "meaning", "purpose", "function"})
PORT_ROW = "port"
REGISTER_FIELD_ROW = "register_field"
_IDENTIFIER = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
_WIDTH_INTEGER = re.compile(r"^\d+$")
_WIDTH_RANGE = re.compile(r"^\[?\s*(\d+)\s*:\s*(\d+)\s*\]?$")
_DIRECTION = {
    "i": "input", "in": "input", "input": "input",
    "o": "output", "out": "output", "output": "output",
    "io": "inout", "inout": "inout", "bidirectional": "inout",
}
_SOURCE_ROLE = {
    "manager": "manager", "master": "manager", "initiator": "manager",
    "requester": "manager", "transmitter": "manager", "tx": "manager",
    "subordinate": "subordinate", "slave": "subordinate", "target": "subordinate",
    "completer": "subordinate", "receiver": "subordinate", "rx": "subordinate",
}


def _header_key(value):
    """Normalize a table header for deterministic role matching.

    Args:
        value: Raw table-header text.

    Returns:
        Lowercase, whitespace-normalized header text.
    """
    return " ".join(str(value or "").strip().lower().replace("_", " ").split())


def _column_index(columns, accepted):
    """Return the first table-column index carrying one accepted header.

    Args:
        columns: Raw table headers.
        accepted: Normalized header names accepted for one semantic field.

    Returns:
        The matching zero-based index, or None.
    """
    return next((index for index, value in enumerate(columns)
                 if _header_key(value) in accepted), None)


def _cell(row, index):
    """Read a stripped table cell without failing on ragged extracted rows.

    Args:
        row: Structured table row.
        index: Optional column index.

    Returns:
        The stripped cell string, or None when absent or empty.
    """
    if index is None or index >= len(row):
        return None
    value = str(row[index] or "").strip()
    return value or None


def parse_width(value):
    """Parse an explicit integral width or bit range without guessing expressions.

    Args:
        value: Raw table width cell.

    Returns:
        A positive integer width when deterministic, otherwise the original string or None.
    """
    text = str(value or "").strip()
    if not text:
        return None
    if _WIDTH_INTEGER.fullmatch(text):
        width = int(text)
        return width if width > 0 else text
    bit_range = _WIDTH_RANGE.fullmatch(text)
    if bit_range:
        return abs(int(bit_range.group(1)) - int(bit_range.group(2))) + 1
    return text


def parse_direction(value):
    """Normalize only explicit input, output, or bidirectional table values.

    Args:
        value: Raw direction cell.

    Returns:
        ``input``, ``output``, ``inout``, or None when the table is not explicit.
    """
    return _DIRECTION.get(_header_key(value))


def parse_source_role(value):
    """Normalize the interface role that a table names as a signal's driver.

    Args:
        value: Raw source or driver cell.

    Returns:
        ``manager``, ``subordinate``, or None when the cell names no interface role.
    """
    return _SOURCE_ROLE.get(_header_key(value))


def _parsed_cell(row, indexes, parser):
    """Return the first value one parser accepts, with the cell that stated it.

    Args:
        row: Structured table row.
        indexes: Candidate column indexes in preference order.
        parser: Callable returning a normalized value or None.

    Returns:
        ``(parsed_value, source_cell)``, or ``(None, None)`` when no column states it.
    """
    for index in indexes:
        value = _cell(row, index)
        parsed = parser(value)
        if parsed:
            return parsed, value
    return None, None


def _signal_name(value):
    """Return a clean identifier-shaped table value or an empty string.

    Args:
        value: Candidate signal-name cell.

    Returns:
        Clean source spelling, or an empty string when the cell is not an identifier.
    """
    text = str(value or "").strip().strip(",;:")
    if (not text or _header_key(text) in NAME_HEADERS or "(" in text
            or len(text.split()) > 1 or not _IDENTIFIER.fullmatch(text)):
        return ""
    return text


def _signal_record(record, signal_id, name, row_kind, row_index, **stated):
    """Build one signal record with the provenance every extractor must carry.

    Args:
        record: Specification chunk the signal was read from.
        signal_id: Stable identifier for this signal.
        name: Source spelling of the signal.
        row_kind: ``port`` or ``register_field``.
        row_index: One-based position within the chunk.
        stated: Fields the caller actually read, overriding the unstated defaults.

    Returns:
        A signal record whose keys are in stable serialization order.
    """
    signal = {
        "signal_id": signal_id,
        "id": signal_id,
        "name": name,
        "original_name": name,
        "normalized_name": normalize_identifier(name),
        "normalized_tokens": identifier_tokens(name),
        "width": None,
        "direction": None,
        "source_role": None,
        "source_role_source": None,
        "row_kind": row_kind,
        "description": None,
        "document_id": record["document_id"],
        "section_id": record.get("section_id"),
        "section_title": record.get("section_title"),
        "subsection_id": record.get("subsection_id"),
        "subsection_title": record.get("subsection_title"),
        "table_id": None,
        "table_label": None,
        "table_caption": None,
        "row_index": row_index,
        "page": record["page"],
        "source_file": record["source_file"],
        "chunk_id": record["chunk_id"],
    }
    # Updating in place keeps the key order above, which the artifact diff depends on.
    signal.update(stated)
    return signal


def signals_from_table(record):
    """Extract structured signal rows from one table chunk.

    Args:
        record: Structured table chunk emitted by ``ingest.py``.

    Returns:
        Stable signal records in source row order.
    """
    if record.get("chunk_type") != "table":
        return []
    columns = record["columns"]
    rows = record["rows"]
    explicit_index = _column_index(columns, EXPLICIT_NAME_HEADERS)
    name_index = next((index for index in (explicit_index,
                                           _column_index(columns, GENERIC_NAME_HEADERS))
                       if index is not None), None)
    if name_index is None:
        return []
    width_index = _column_index(columns, WIDTH_HEADERS)
    direction_index = _column_index(columns, DIRECTION_HEADERS)
    source_index = _column_index(columns, SOURCE_HEADERS)
    address_index = _column_index(columns, ADDRESS_HEADERS)
    # Columns alone admit a table: a signal column, or a name beside width/source/address.
    if all(index is None for index in (explicit_index, width_index, source_index,
                                       address_index)):
        return []
    if explicit_index is not None or direction_index is not None or source_index is not None:
        row_kind = PORT_ROW
    else:
        row_kind = REGISTER_FIELD_ROW
    description_index = _column_index(columns, DESCRIPTION_HEADERS)
    document_id = record["document_id"]
    table_id = record["table_id"]
    table_label = record["table_label"]
    signals = []
    occurrences = {}
    for row_index, row in enumerate(rows, start=1):
        original_name = _signal_name(_cell(row, name_index))
        # In an address table a row without an address is a group label, not a register.
        if not original_name or (address_index is not None and not _cell(row, address_index)):
            continue
        normalized_name = normalize_identifier(original_name)
        if not normalized_name:
            continue
        base_id = f"spec::signal::{document_id}::{table_label or 'unlabelled'}::{normalized_name}"
        occurrences[base_id] = occurrences.get(base_id, 0) + 1
        signal_id = (base_id if occurrences[base_id] == 1 else
                     f"{base_id}::{occurrences[base_id]}")
        width_source = _cell(row, width_index)
        direction_source = _cell(row, direction_index)
        source_role, source_role_source = _parsed_cell(
            row, (source_index, direction_index), parse_source_role)
        direction = (parse_direction(direction_source)
                     or parse_direction(_cell(row, source_index)))
        signal = _signal_record(
            record, signal_id, original_name, row_kind, row_index,
            width=parse_width(width_source), direction=direction,
            source_role=source_role, source_role_source=source_role_source,
            description=_cell(row, description_index),
            table_id=table_id, table_label=table_label, table_caption=record["caption"])
        signals.append(signal)
    return signals


def build_spec_signals(records):
    """Build the complete idempotent table-derived specification signal inventory.

    Args:
        records: Specification chunks in deterministic corpus order.

    Returns:
        Signal records with one stable ID each.
    """
    records = list(records)
    signals = []
    seen = set()
    for record in records:
        for signal in signals_from_table(record):
            if signal["signal_id"] in seen:
                continue
            seen.add(signal["signal_id"])
            signals.append(signal)
    return signals


def save_spec_signals(signals, path=cfg.SPEC_SIGNALS_PATH):
    """Atomically replace the generated specification signal artifact.

    Args:
        signals: Structured signal records to persist.
        path: Destination JSON path.

    Returns:
        None.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    with open(temporary, "w", encoding="utf-8") as handle:
        json.dump({"schema_version": SCHEMA_VERSION, "signals": list(signals)},
                  handle, ensure_ascii=False, indent=1)
    temporary.replace(path)


def main():
    """Build ``spec_signals.json`` from current structured table chunks.

    Returns:
        None.
    """
    records = load_chunks()
    signals = build_spec_signals(records)
    save_spec_signals(signals)
    kinds = Counter(signal["row_kind"] for signal in signals)
    print(f"====  wrote {cfg.SPEC_SIGNALS_PATH.relative_to(cfg.ROOT)}: {len(signals)} rows ("
          + ", ".join(f"{count} {kind}" for kind, count in sorted(kinds.items())) + ")")


if __name__ == "__main__":
    main()
