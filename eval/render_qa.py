"""Render the benchmark question set as a readable Q&A markdown document.

Run from the repo root: ``python eval/render_qa.py``. Reads eval/question_set.json
plus the ingested chunk stores and rewrites eval/QUESTION_SET.md so the prose file
can never drift from the chunk ids the benchmark actually scores.
"""

import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
import configure as cfg
QUESTION_SET = ROOT / "eval" / "question_set.json"
MARKDOWN = ROOT / "eval" / "QUESTION_SET.md"
SNIPPET_CHARS = 1100


def load_chunks(path, key="text"):
    """Index one JSONL chunk store by chunk id.

    Args:
        path: JSONL store path.
        key: Field holding the chunk body.

    Returns:
        Chunk id to record mapping, or an empty mapping when the store is absent.
    """
    if not path.exists():
        return {}
    with open(path, encoding="utf-8") as handle:
        records = [json.loads(line) for line in handle if line.strip()]
    return {record["chunk_id"]: {**record, "body": record.get(key, "")}
            for record in records}


def spec_label(record):
    """Describe one spec chunk by document, page, and section.

    Args:
        record: Spec chunk record.

    Returns:
        Human-readable source label.
    """
    page = record.get("page") or record.get("start_page")
    section = record.get("section_name") or record.get("subsection_title") or ""
    return f"{record.get('doc_name', record.get('document_id', ''))}, p.{page} — {section}"


def rtl_label(record):
    """Describe one RTL chunk by file and line range.

    Args:
        record: RTL chunk record.

    Returns:
        Human-readable source label.
    """
    name = Path(record.get("file", "")).name or record.get("module", "")
    start, end = record.get("start_line"), record.get("end_line")
    lines = f":{start}-{end}" if start and end else ""
    return f"{name}{lines} — {record.get('context_header', '')}"


def snippet(text):
    """Collapse a chunk body into one quotable block.

    Args:
        text: Raw chunk body.

    Returns:
        Whitespace-normalized excerpt bounded by ``SNIPPET_CHARS``.
    """
    body = " ".join(text.split())
    return body if len(body) <= SNIPPET_CHARS else body[:SNIPPET_CHARS].rstrip() + " …"


def render_case(case, index, spec_chunks, rtl_chunks):
    """Render one question, its expected chunks, and its verified answer.

    Args:
        case: Gold case record.
        index: One-based question number.
        spec_chunks: Spec chunk index.
        rtl_chunks: RTL chunk index.

    Returns:
        Markdown lines for this question.
    """
    lines = [f"### Q{index}. {case['id']}", "",
             f"**Question:** {case['question']}", "",
             f"**Route:** `{case['expected_query_type']}` · **signal naming:** "
             f"{case['naming']} · **abstention correct:** "
             f"{'yes' if case['abstention_is_correct'] else 'no'}", "",
             f"**Answer:** {case['truth']}", ""]
    for label, ids, chunks, describe in (
            ("Spec chunks", case["relevant_spec_ids"], spec_chunks, spec_label),
            ("RTL chunks", case["relevant_rtl_ids"], rtl_chunks, rtl_label)):
        if not ids:
            continue
        lines.append(f"**{label}:**")
        lines.append("")
        for chunk_id in ids:
            record = chunks.get(chunk_id)
            lines.append(f"- `{chunk_id}` — {describe(record) if record else 'NOT FOUND'}")
            if record:
                lines.append(f"  > {snippet(record['body'])}")
        lines.append("")
    return lines


def main():
    """Write the markdown Q&A rendering of the question set.

    Returns:
        None.
    """
    with open(QUESTION_SET, encoding="utf-8") as handle:
        cases = json.load(handle)
    spec_chunks = load_chunks(cfg.CHUNKS_PATH)
    rtl_chunks = load_chunks(cfg.RTL_CHUNKS_PATH)

    routes = ["SPEC", "RTL", "COMPARISON"]
    lines = ["# Dual-RAG Question Set", "",
             "Development labels only; this catalogue is not an independently approved release holdout.", "",
             f"{len(cases)} development questions: "
             + ", ".join(f"{sum(c['expected_query_type'] == r for c in cases)} {r.lower()}"
                         for r in routes) + ".",
             "",
             "Each question lists alternative answer-bearing chunks; optional groups split "
             "independent facts. Comparison questions score both domains. `naming` marks "
             "whether the question uses exact RTL signal names or everyday wording. Generated by "
             "`python eval/render_qa.py` from `eval/question_set.json` — edit the JSON, "
             "not this file.", ""]
    for route in routes:
        lines += [f"## {route} questions", ""]
        for index, case in enumerate(
                [c for c in cases if c["expected_query_type"] == route], start=1):
            lines += render_case(case, index, spec_chunks, rtl_chunks)
    MARKDOWN.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {MARKDOWN} ({len(cases)} questions)")


if __name__ == "__main__":
    main()
